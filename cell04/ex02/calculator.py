first_num = int(input("Give me a first number : "))
second_num = int(input("Give me a second number : "))
print("Thank you!")

print(f"{first_num} + {second_num} = {first_num + second_num}")
print(f"{first_num} - {second_num} = {first_num - second_num}")
print(f"{first_num} / {second_num} = {first_num / second_num}")
print(f"{first_num} x {second_num} = {first_num * second_num}")